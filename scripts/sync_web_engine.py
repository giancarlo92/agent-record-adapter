# Part of Agent Record Adapter (see NOTICE).
"""Keeps crates/web-engine/cli (agent-browser carried inside agent-record.exe)
in step with the agent-browser submodule:

- its Cargo.toml takes upstream's version and dependencies
  (vendor/agent-browser/cli/Cargo.toml), never edited by hand;
- with --pin, the dependency versions in our Cargo.lock are set to the ones in
  upstream's Cargo.lock wherever cargo allows it, so agent-browser is built
  with the same libraries as upstream's own release.

    python scripts/sync_web_engine.py           # write the manifest
    python scripts/sync_web_engine.py --check   # fail if it is not in step
    python scripts/sync_web_engine.py --pin     # write it and pin the lock
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "vendor" / "agent-browser" / "cli"
OURS = ROOT / "crates" / "web-engine" / "cli" / "Cargo.toml"

HEADER = """# Part of Agent Record Adapter (see NOTICE).
# agent-browser, from its unmodified sources (vendor/agent-browser/cli/src), as
# a library carried inside agent-record.exe. Nothing here is a copy: the build
# script points upstream's main.rs and its modules at the submodule (see
# crates/embed_root.rs). This folder sits one level down (web-engine/cli) so
# upstream's paths relative to its package ("../packages/dashboard/out") land
# in web-engine/packages, which the build script fills.
# Generated by scripts/sync_web_engine.py from vendor/agent-browser/cli/Cargo.toml:
# never edit by hand.
"""


def section(text, name):
    found = re.search(r"^\[" + re.escape(name) + r"\]\n(.*?)(?=^\[|\Z)", text, re.S | re.M)
    return found.group(1).strip() + "\n" if found else ""


def manifest():
    text = (UPSTREAM / "Cargo.toml").read_text(encoding="utf-8")
    version = re.search(r'^version = "([^"]+)"', text, re.M).group(1)
    parts = [
        HEADER,
        "[package]\n",
        'name    = "agent-record-web-engine"\n',
        f'version = "{version}"\n',
        'edition = "2021"\n',
        'license = "Apache-2.0"\n',
        "publish = false\n",
        'build   = "build.rs"\n\n',
        "[lib]\n",
        'name = "agent_record_web_engine"\n',
        'path = "src/lib.rs"\n',
    ]
    for name in [
        "dependencies",
        "target.'cfg(unix)'.dependencies",
        "target.'cfg(windows)'.dependencies",
        "build-dependencies",
    ]:
        body = section(text, name)
        if body:
            parts.append(f"\n[{name}]\n{body}")
    return "".join(parts)


def lock_versions(path):
    text = path.read_text(encoding="utf-8")
    found = {}
    for match in re.finditer(r'\[\[package\]\]\nname = "([^"]+)"\nversion = "([^"]+)"', text):
        found.setdefault(match.group(1), set()).add(match.group(2))
    return found


def pin():
    upstream = lock_versions(UPSTREAM / "Cargo.lock")
    pinned = skipped = 0
    for name, versions in sorted(lock_versions(ROOT / "Cargo.lock").items()):
        wanted = upstream.get(name)
        if not wanted or versions & wanted or len(versions) != 1 or len(wanted) != 1:
            continue
        ours, theirs = next(iter(versions)), next(iter(wanted))
        done = subprocess.run(
            ["cargo", "update", "-p", f"{name}@{ours}", "--precise", theirs],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )
        if done.returncode == 0:
            pinned += 1
        else:
            skipped += 1
    print(f"pinned {pinned} dependencies to upstream's versions, {skipped} kept (others need them newer)")


def main():
    text = manifest()
    if "--check" in sys.argv:
        if OURS.read_text(encoding="utf-8") != text:
            print("crates/web-engine/cli/Cargo.toml is not in step: run python scripts/sync_web_engine.py")
            sys.exit(1)
        print("crates/web-engine/cli/Cargo.toml is in step with upstream")
        return
    OURS.write_text(text, encoding="utf-8", newline="\n")
    print("crates/web-engine/cli/Cargo.toml written")
    if "--pin" in sys.argv:
        pin()


if __name__ == "__main__":
    main()
