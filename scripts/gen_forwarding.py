# Part of Agent Record Adapter (see NOTICE).
"""Generate the forwarding impls of the four upstream PlatformAdapter traits.

Reads the trait definitions from the unmodified agent-desktop submodule and
writes crates/windows-adapter/src/forward.rs: every method of ObservationOps,
ActionOps, InputOps and SystemOps forwards to the inner upstream adapter,
except the ones listed in OURS, which call `self.ours_<name>(...)` (written by
hand in hooks.rs). Run again after every upstream update; `--check` fails when
the file on disk is out of date (a new upstream method would otherwise fall to
its not-supported default instead of reaching WindowsAdapter).
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORE = ROOT / "vendor/agent-desktop/crates/core/src/adapter"
OUT = ROOT / "crates/windows-adapter/src/forward.rs"
TRAITS = [("ObservationOps", "observation.rs"), ("ActionOps", "actions.rs"),
          ("InputOps", "input.rs"), ("SystemOps", "system.rs")]
# Methods our background layer answers first (see hooks.rs).
OURS = {"execute_action", "press_key_for_window", "launch_app", "window_op",
        "observe_tree", "get_live_element", "get_live_actions", "list_windows", "capture_signal_baseline",
        "query_app_inventory", "acquire_interaction_lease", "get_live_value"}


def trait_body(src, name):
    m = re.search(r"pub trait %s\b[^{]*\{" % name, src)
    i, depth = m.end(), 1
    start = i
    while depth:
        c = src[i]
        depth += c == "{"
        depth -= c == "}"
        i += 1
    return src[start:i - 1]


def methods(body):
    out, i = [], 0
    for m in re.finditer(r"(?m)^    fn (\w+)", body):
        j, depth = m.end(), 0
        while True:
            c = body[j]
            if c in "(<[":
                depth += 1
            elif c in ")>]":
                depth -= 1 if not (c == ">" and body[j - 1] == "-") else 0
            elif depth == 0 and c in "{;":
                break
            j += 1
        sig = body[m.start():j].strip()
        out.append((m.group(1), sig))
    return out


def qualify(sig):
    # `crate::adapter::X` are crate-private re-exports of root items.
    sig = re.sub(r"crate::adapter::([A-Z]\w*)", r"core::\1", sig)
    return re.sub(r"\bcrate::", "core::", sig)


def params(sig):
    inner = sig[sig.index("(") + 1:]
    depth, cur, parts = 0, "", []
    for c in inner:
        if c in "(<[":
            depth += 1
        elif c in ")>]":
            if depth == 0 and c == ")":
                parts.append(cur)
                break
            depth -= 1
        if c == "," and depth == 0:
            parts.append(cur)
            cur = ""
            continue
        cur += c
    names = []
    for p in parts:
        p = p.strip()
        if not p or "self" in p.split(":")[0]:
            continue
        names.append(p.split(":")[0].strip())
    return names


def render():
    lines = ["// Part of Agent Record Adapter (see NOTICE).",
             "// @generated by scripts/gen_forwarding.py from the unmodified agent-desktop traits:",
             "// do not edit by hand.",
             "#![allow(clippy::too_many_arguments, unused_imports)]",
             "use agent_desktop_core as core;",
             "use agent_desktop_core::*;",
             "use agent_desktop_core::actions::action_request::ActionRequest;",
             "use crate::WindowsAdapter;", ""]
    for trait, file in TRAITS:
        src = (CORE / file).read_text(encoding="utf-8")
        body = trait_body(src, trait)
        lines.append("impl core::%s for WindowsAdapter {" % trait)
        for name, sig in methods(body):
            sig = qualify(sig)
            names = params(sig)
            fixed = sig
            args = []
            for n in names:
                clean = n.lstrip("_").replace("mut ", "") or "arg"
                fixed = re.sub(r"\b%s\s*:" % re.escape(n), clean + ":", fixed, count=1)
                args.append(clean)
            target = "self.ours_%s" % name if name in OURS else "self.inner.%s" % name
            lines.append("    %s {" % fixed)
            lines.append("        %s(%s)" % (target, ", ".join(args)))
            lines.append("    }")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


text = render()
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        sys.exit("forward.rs is out of date: run python scripts/gen_forwarding.py")
else:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT)
